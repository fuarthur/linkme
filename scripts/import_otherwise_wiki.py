#!/usr/bin/env python3
"""Build LinkMe's offline Wiki snapshot from three public OtherWise data files.

No network requests, OtherWise imports, caches, authored descriptions, or user files
are needed. All validation completes before any generated file is replaced.
"""
from __future__ import annotations

import argparse
from collections import Counter
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import sys
import unicodedata
from urllib.parse import urlparse


REPO_ROOT = Path(__file__).resolve().parents[1]
HEADER = "wikidata_id\ttitle\tdomain\tdescription\tvalue\n"
QID = re.compile(r"Q[1-9][0-9]*\Z")
MAX_STORED_UNITS = 40
# These entities mean more than the existing starter alias would preserve.
# QIDs, rather than fuzzy label rules, make this exception explicit and reviewable.
LEGACY_MEANING_COLLISIONS = {
    "Q189900": "Information security covers more than the Cybersecurity starter.",
    "Q6607": "Guitar names the instrument, rather than the Playing guitar activity.",
    "Q1081491": "Football includes multiple codes, rather than only the Soccer starter.",
    "Q114397581": "Weightlifting denotes the sport/exercise, rather than generic Strength training.",
    "Q39162": "Open source includes practices beyond the Open-source software starter.",
}
EXPANDED_GUIDE_URL = "https://meta.wikimedia.org/wiki/List_of_articles_every_Wikipedia_should_have/Expanded"
LICENSES = {
    "labels_and_descriptions": "CC0-1.0",
    "selection_and_grouping": "CC-BY-SA-4.0",
}
PUBLIC_SOURCE_NAMES = ("topics.json", "catalog_metadata.json", "README.md")


def normalized(value: str) -> str:
    """Match the existing NFKC, whitespace, and case-insensitive stored-label key."""
    return " ".join(unicodedata.normalize("NFKC", value).split()).lower()


def utf16_units(value: str) -> int:
    return len(value.encode("utf-16-le")) // 2


def checked_text(value: object, field: str, *, description: bool = False) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{field} must be a string")
    if any(0xD800 <= ord(char) <= 0xDFFF for char in value):
        raise ValueError(f"{field} contains an unpaired surrogate")
    allowed_controls = "\t\r\n" if description else ""
    if any(unicodedata.category(char) == "Cc" and char not in allowed_controls for char in value):
        raise ValueError(f"{field} contains a control character")
    if not any(unicodedata.category(char)[0] not in ("C", "Z") and unicodedata.category(char) not in ("Mn", "Me") for char in value):
        raise ValueError(f"{field} must have visible content")
    if description:
        return " ".join(value.split())
    return value


def positive_integer(value: object, field: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise ValueError(f"{field} must be a positive integer")
    return value


def checked_public_url(value: object, field: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{field} must be a public Wikimedia URL")
    url = urlparse(value)
    if url.scheme != "https" or url.hostname not in ("en.wikipedia.org", "meta.wikimedia.org", "www.wikidata.org"):
        raise ValueError(f"{field} must be a public Wikimedia HTTPS URL")
    if url.username or url.password or url.port or not url.path.startswith("/wiki/"):
        raise ValueError(f"{field} is not a canonical public Wikimedia URL")
    return value


def unique_json_object(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def load_json(data: bytes, name: str) -> object:
    try:
        return json.loads(
            data.decode("utf-8"), object_pairs_hook=unique_json_object,
            parse_constant=lambda value: (_ for _ in ()).throw(ValueError(f"Invalid JSON constant: {value}")),
        )
    except (UnicodeError, ValueError) as error:
        raise ValueError(f"Invalid {name}: {error}") from error


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")


def deterministic_gzip(data: bytes) -> bytes:
    output = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=output, compresslevel=9, mtime=0) as stream:
        stream.write(data)
    return output.getvalue()


def kotlin_string(value: str) -> str:
    # JSON escaping is compatible for these Kotlin string characters, except '$'.
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def generated_references(rows: list[dict]) -> bytes:
    references = [row for row in rows if row["value"] != row["title"]]
    lines = [
        "// Generated by scripts/import_otherwise_wiki.py. Do not edit by hand.",
        "// Wikidata labels: CC0. Derived selection: CC BY-SA 4.0; see assets/wiki-topics/NOTICE.txt.",
        "package com.ams.linkme.domain", "", "import java.util.Locale", "",
        "/** Small synchronous lookup for labels whose stored Wiki identity needs a reference. */",
        "object WikiTopicReferences {",
        f"    const val TOPIC_COUNT = {len(rows)}", "",
        "    private val labels = mapOf(",
    ]
    for row in sorted(references, key=lambda item: item["wikidata_id"]):
        lines.append(f"        {kotlin_string(row['value'].lower())} to {kotlin_string(row['title'])},")
    lines += [
        "    )", "",
        "    fun label(value: String): String? = labels[value.lowercase(Locale.ROOT)]", "",
        "    fun canonical(value: String): String? {",
        "        val key = value.lowercase(Locale.ROOT)",
        "        if (!labels.containsKey(key)) return null",
        '        return "wiki:Q" + key.substring(6)',
        "    }", "}", "",
    ]
    return "\n".join(lines).encode("utf-8")


def build_outputs(source: Path) -> tuple[dict[str, bytes], bytes, dict]:
    # This whitelist is the complete read surface in OtherWise; do not recurse.
    source_bytes = {name: (source / "data" / name).read_bytes() for name in PUBLIC_SOURCE_NAMES}
    source_bytes["README.md"].decode("utf-8")
    records = load_json(source_bytes["topics.json"], "topics.json")
    metadata = load_json(source_bytes["catalog_metadata.json"], "catalog_metadata.json")
    if not isinstance(records, list) or not isinstance(metadata, dict):
        raise ValueError("Expected a topic array and catalog metadata object")
    if metadata.get("topic_count") != len(records):
        raise ValueError("Catalog metadata topic_count does not match topics.json")
    snapshot_date = metadata.get("snapshot_date")
    if not isinstance(snapshot_date, str) or not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", snapshot_date):
        raise ValueError("Catalog metadata requires its public snapshot_date")
    source_counts = Counter()
    rows = []
    provenance = {}
    seen_ids = set()
    for position, record in enumerate(records, start=1):
        if not isinstance(record, dict) or record.get("source") not in ("Wikidata", "ProductSpace"):
            raise ValueError(f"Record {position} has an unknown or missing source")
        source_counts[record["source"]] += 1
        if record["source"] != "Wikidata":
            continue  # Do not copy or interpret the separately authored descriptions.
        qid = record.get("wikidata_id")
        if not isinstance(qid, str) or not QID.fullmatch(qid):
            raise ValueError(f"Record {position} has an invalid Wikidata ID")
        if qid in seen_ids:
            raise ValueError(f"Duplicate Wikidata ID: {qid}; no record was silently dropped")
        seen_ids.add(qid)
        title = checked_text(record.get("topic"), f"{qid}.topic")
        domain = checked_text(record.get("domain"), f"{qid}.domain")
        description = checked_text(record.get("description"), f"{qid}.description", description=True)
        source_url = checked_public_url(record.get("source_url"), f"{qid}.source_url")
        if source_url != f"https://www.wikidata.org/wiki/{qid}":
            raise ValueError(f"{qid}.source_url does not match the entity ID")
        record_source = {
            "wikidata_id": qid,
            "source": "Wikidata",
            "source_url": source_url,
            "source_revision": positive_integer(record.get("source_revision"), f"{qid}.source_revision"),
            "list_revision": positive_integer(record.get("list_revision"), f"{qid}.list_revision"),
            "list_section": checked_text(record.get("list_section"), f"{qid}.list_section"),
            "subsection": checked_text(record.get("subsection"), f"{qid}.subsection"),
        }
        if "list_url" in record:
            record_source["list_url"] = checked_public_url(record["list_url"], f"{qid}.list_url")
        else:
            # The retained guide rows record a Meta revision but no URL; retain the
            # exact revision and attach the known public guide as a documented fallback.
            record_source["list_url"] = EXPANDED_GUIDE_URL
            record_source["list_url_inferred_from_retained_guide"] = True
        for field in ("wikipedia_url",):
            if field in record:
                record_source[field] = checked_public_url(record[field], f"{qid}.{field}")
        for field in ("guide_title", "selection_source"):
            if field in record:
                record_source[field] = checked_text(record[field], f"{qid}.{field}")
        provenance[qid] = record_source
        rows.append({"wikidata_id": qid, "title": title, "domain": domain, "description": description})
    expected_source_counts = metadata.get("source_counts")
    if not isinstance(expected_source_counts, dict) or any(
        expected_source_counts.get(name, 0) != source_counts[name] for name in ("Wikidata", "ProductSpace")
    ):
        raise ValueError("Catalog metadata source_counts does not match topics.json")
    if not rows:
        raise ValueError("No public Wikidata rows were found")
    title_counts = Counter(normalized(row["title"]) for row in rows)
    collision_groups = sum(count > 1 for count in title_counts.values())
    long_count = collision_count = legacy_count = reserved_count = 0
    used_values = set()
    for row in rows:
        title = row["title"]
        is_long = utf16_units(title) > MAX_STORED_UNITS or utf16_units(normalized(title)) > MAX_STORED_UNITS
        is_collision = title_counts[normalized(title)] > 1
        is_legacy_collision = row["wikidata_id"] in LEGACY_MEANING_COLLISIONS
        is_reserved_title = bool(re.fullmatch(r"wiki:q[1-9][0-9]*", normalized(title)))
        long_count += is_long
        collision_count += is_collision
        legacy_count += is_legacy_collision
        reserved_count += is_reserved_title
        value = f"wiki:{row['wikidata_id']}" if is_long or is_collision or is_legacy_collision or is_reserved_title else title
        if not 1 <= utf16_units(normalized(value)) <= MAX_STORED_UNITS:
            raise ValueError(f"{row['wikidata_id']} has no schema-compatible stored identity")
        if normalized(value) in used_values:
            raise ValueError(f"Duplicate normalized stored value: {value}")
        used_values.add(normalized(value))
        row["value"] = value
    rows.sort(key=lambda row: (normalized(row["title"]), row["title"], row["wikidata_id"]))
    domains = dict(sorted(Counter(row["domain"] for row in rows).items()))
    topic_data = (HEADER + "".join(
        "\t".join(row[field] for field in ("wikidata_id", "title", "domain", "description", "value")) + "\n"
        for row in rows
    )).encode("utf-8")
    record_data = ("".join(
        json.dumps(provenance[row["wikidata_id"]], ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n"
        for row in rows
    )).encode("utf-8")
    references = generated_references(rows)
    topic_asset = deterministic_gzip(topic_data)
    provenance_asset = deterministic_gzip(record_data)
    manifest = {
        "format_version": 1,
        "snapshot_date": snapshot_date,
        "topic_count": len(rows),
        "domain_count": len(domains),
        "domains": domains,
        "excluded_authored_topic_count": source_counts["ProductSpace"],
        "reference_count": sum(row["value"] != row["title"] for row in rows),
        "long_title_reference_count": long_count,
        "normalized_title_collision_groups": collision_groups,
        "normalized_title_collision_record_count": collision_count,
        "legacy_starter_meaning_collision_count": legacy_count,
        "reserved_reference_title_count": reserved_count,
        "legacy_starter_meaning_collision_reasons": {
            qid: reason for qid, reason in LEGACY_MEANING_COLLISIONS.items() if qid in seen_ids
        },
        "maximum_title_utf16_units": max(utf16_units(row["title"]) for row in rows),
        "source_catalog_topic_count": len(records),
        "sources": {
            f"data/{name}": {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
            for name, data in source_bytes.items()
        },
        "artifacts": {
            "topics.tsv.gz": {"sha256": hashlib.sha256(topic_asset).hexdigest(), "bytes": len(topic_asset), "uncompressed_bytes": len(topic_data)},
            "record-provenance.jsonl.gz": {"sha256": hashlib.sha256(provenance_asset).hexdigest(), "bytes": len(provenance_asset), "uncompressed_bytes": len(record_data)},
            "WikiTopicReferences.kt": {"sha256": hashlib.sha256(references).hexdigest(), "bytes": len(references)},
        },
        "licenses": LICENSES,
        "license_urls": {
            "labels_and_descriptions": "https://www.wikidata.org/wiki/Wikidata:Licensing",
            "selection_and_grouping": "https://creativecommons.org/licenses/by-sa/4.0/",
        },
        "credits": ["Wikidata contributors", "Wikipedia and Wikimedia contributors", "OtherWise public catalog selection and domain grouping"],
        "list_revisions": metadata.get("list_revisions", {}),
        "public_selection_urls": [
            "https://en.wikipedia.org/wiki/Wikipedia:Vital_articles/Level/5", EXPANDED_GUIDE_URL,
        ],
        "changes": [
            "Select only records explicitly sourced to Wikidata; omit all separately authored records.",
            "Retain titles, IDs, domains and public record revisions; collapse description whitespace for TSV.",
            "Sort deterministically; encode long, normalized-colliding and five broader legacy-alias entities as compact Wiki references.",
        ],
    }
    notice = """LinkMe offline Wiki topic library

Credits: Wikidata contributors; Wikipedia and Wikimedia contributors; OtherWise
public catalog selection and domain grouping. OtherWise is the immediate public
snapshot source. Exact input SHA256 hashes, snapshot date, counts, list revisions
and LinkMe transformations are in provenance.json. Each imported entity's public
source URL, Wikidata revision, list revision and subsection are preserved in
record-provenance.jsonl.gz. Retained guide rows without a recorded list URL use
the credited Wikimedia expanded-guide URL; that inference is explicitly marked.

Wikidata structured labels and short descriptions are CC0:
https://www.wikidata.org/wiki/Wikidata:Licensing
https://creativecommons.org/publicdomain/zero/1.0/

The derived topic selection and domain grouping are distributed under CC BY-SA
4.0, with credit to the contributors and OtherWise named above:
https://creativecommons.org/licenses/by-sa/4.0/
https://en.wikipedia.org/wiki/Wikipedia:Vital_articles/Level/5
https://meta.wikimedia.org/wiki/List_of_articles_every_Wikipedia_should_have/Expanded

LinkMe modifications: omit the separately authored records; retain every imported
Wikidata identity and full title; normalize description whitespace for TSV; sort
and compress reproducibly; add compact storage references for long/colliding
labels and five broader meanings that conflict with existing starter aliases.
The modified selection/grouping remains CC BY-SA 4.0. Article bodies, authored
OtherWise descriptions, implementation code and personal data are not included.
No endorsement by Wikimedia, Wikipedia, Wikidata or OtherWise is implied.
"""
    return {
        "topics.tsv.gz": topic_asset,
        "record-provenance.jsonl.gz": provenance_asset,
        "provenance.json": json_bytes(manifest),
        "NOTICE.txt": notice.encode("utf-8"),
    }, references, manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=REPO_ROOT.parent / "OtherWise", help="Read-only OtherWise public-data project root")
    parser.add_argument("--output-dir", type=Path, default=REPO_ROOT / "app/src/main/assets/wiki-topics")
    parser.add_argument("--references", type=Path, default=REPO_ROOT / "app/src/main/java/com/ams/linkme/domain/WikiTopicReferences.kt")
    parser.add_argument("--check", action="store_true", help="Validate public inputs and require byte-identical generated files without writing")
    args = parser.parse_args()
    try:
        source_root = args.source.resolve()
        target_paths = [args.output_dir / name for name in ("topics.tsv.gz", "record-provenance.jsonl.gz", "provenance.json", "NOTICE.txt")]
        target_paths.append(args.references)
        if any(path.resolve().is_relative_to(source_root) for path in target_paths):
            raise ValueError("Generated outputs cannot be placed inside the read-only OtherWise source project")
        if len({path.resolve() for path in target_paths}) != len(target_paths):
            raise ValueError("Generated outputs must have distinct destination paths")
        outputs, references, manifest = build_outputs(args.source)
        destinations = {args.output_dir / name: data for name, data in outputs.items()}
        destinations[args.references] = references
        if args.check:
            changed = [str(path) for path, data in destinations.items() if not path.is_file() or path.read_bytes() != data]
            if changed:
                print("Wiki snapshot is missing or stale:\n" + "\n".join(changed), file=sys.stderr)
                return 1
        else:
            for path, data in destinations.items():
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
        action = "Verified" if args.check else "Generated"
        print(f"{action} {manifest['topic_count']} Wiki topics across {manifest['domain_count']} domains; {manifest['reference_count']} compact references.")
        return 0
    except (OSError, ValueError, TypeError) as error:
        print(f"Wiki snapshot import failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
